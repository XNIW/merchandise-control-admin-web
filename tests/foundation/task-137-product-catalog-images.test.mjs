function copyBytes(bytes) {
  return Uint8Array.from(bytes);
}

function markerOffset(bytes, marker) {
  for (let index = 2; index < bytes.length - 1; index += 1) {
    if (bytes[index] === 0xff && bytes[index + 1] === marker) return index;
  }
  return -1;
}

function insertAfterSoi(bytes, segment) {
  return Uint8Array.from([...bytes.slice(0, 2), ...segment, ...bytes.slice(2)]);
}

function replaceSegment(bytes, offset, replacement) {
  const originalLength = (bytes[offset + 2] << 8) | bytes[offset + 3];
  return Uint8Array.from([
    ...bytes.slice(0, offset),
    ...replacement,
    ...bytes.slice(offset + 2 + originalLength),
  ]);
}

function jpeg(width, height, options = {}) {
  const frameMarker = options.progressive ? 0xc2 : 0xc0;
  const app1 = options.app1
    ? [0xff, 0xe1, 0x00, 0x08, 0x45, 0x78, 0x69, 0x66, 0x00, 0x00]
    : [];
  const scanBytes = options.multiScan
    ? [
        0x01,
        0x02,
        0xff,
        0xd0,
        0x03,
        0xff,
        0xda,
        0x00,
        0x08,
        0x01,
        0x01,
        0x00,
        0x00,
        0x3f,
        0x00,
        0x04,
        0xff,
        0x00,
        0x05,
      ]
    : [0x01, 0x02, 0xff, 0x00, 0x03];
  return Uint8Array.from([
    0xff,
    0xd8,
    ...app1,
    ...(options.segments ?? []).flat(),
    0xff,
    frameMarker,
    0x00,
    0x0b,
    0x08,
    (height >> 8) & 0xff,
    height & 0xff,
    (width >> 8) & 0xff,
    width & 0xff,
    0x01,
    0x01,
    0x11,
    0x00,
    0xff,
    0xda,
    0x00,
    0x08,
    0x01,
    0x01,
    0x00,
    0x00,
    0x3f,
    0x00,
    ...scanBytes,
    0xff,
    0xd9,
    ...(options.trailingBytes ?? []),
  ]);
}

