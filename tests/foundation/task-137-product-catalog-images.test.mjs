test("TASK-137 signed read refreshes once only after Storage auth expiry", async () => {
  let downloadCount = 0;
  let resolveCount = 0;
  const bytes = copyBytes(BASELINE_JPEG);
  const metadata = {
    bytes: bytes.byteLength,
    height: 3,
    mimeType: "image/jpeg",
    sha256: createHash("sha256").update(bytes).digest("hex"),
    width: 2,
  };
  const previousCreateImageBitmap = Object.getOwnPropertyDescriptor(
    globalThis,
    "createImageBitmap",
  );
  Object.defineProperty(globalThis, "createImageBitmap", {
    configurable: true,
    value: async () => ({ close() {}, height: 3, width: 2 }),
    writable: true,
  });

  try {
    const result = await downloadProductImageWithOneAuthRefresh({
      download: async () => {
        downloadCount += 1;
        return downloadCount === 1
          ? new Response(null, { status: 403 })
          : new Response(new Blob([bytes], { type: "image/jpeg" }), {
              status: 200,
            });
      },
      ref: {
        productId: PRODUCT_ID,
        shopId: SHOP_ID,
        variant: "thumb",
        versionId: VERSION_ID,
      },
      resolveSignedRead: async () => {
        resolveCount += 1;
        return {
          cacheScope: "a".repeat(64),
          item: {
            expiresAt: new Date(Date.now() + 300_000).toISOString(),
            metadata,
            productId: PRODUCT_ID,
            signedUrl: `https://example.invalid/read-${resolveCount}`,
            status: "ready",
            variant: "thumb",
            versionId: VERSION_ID,
          },
        };
      },
    });

    assert.equal(downloadCount, 2);
    assert.equal(resolveCount, 2);
    assert.equal(result.blob.type, "image/jpeg");
  } finally {
    if (previousCreateImageBitmap) {
      Object.defineProperty(
        globalThis,
        "createImageBitmap",
        previousCreateImageBitmap,
      );
    } else {
      delete globalThis.createImageBitmap;
    }
  }
});

