test("TASK-137 JPEG parser requires a canonical scan and frame state", () => {
  const noScanOffset = markerOffset(BASELINE_JPEG, 0xda);
  const noScan = Uint8Array.from([
    ...BASELINE_JPEG.slice(0, noScanOffset),
    0xff,
    0xd9,
  ]);
  const losslessFrame = copyBytes(BASELINE_JPEG);
  const frameOffset = markerOffset(losslessFrame, 0xc0);
  losslessFrame[frameOffset + 1] = 0xc3;
  const nestedSoi = insertAfterSoi(BASELINE_JPEG, [0xff, 0xd8]);
  const malformedScan = copyBytes(BASELINE_JPEG);
  const scanOffset = markerOffset(malformedScan, 0xda);
  malformedScan[scanOffset + 2] = 0x00;
  malformedScan[scanOffset + 3] = 0x02;
  const frameAfterScan = Uint8Array.from([
    ...BASELINE_JPEG.slice(0, -2),
    0xff,
    0xc0,
    0x00,
    0x0b,
    0x08,
    0x00,
    0x03,
    0x00,
    0x02,
    0x01,
    0x01,
    0x11,
    0x00,
    0xff,
    0xd9,
  ]);

  for (const malformed of [
    jpeg(800, 600),
    noScan,
    losslessFrame,
    nestedSoi,
    malformedScan,
    frameAfterScan,
  ]) {
    assert.deepEqual(inspectJpeg(malformed), {
      code: "jpeg_structure_invalid",
      ok: false,
    });
  }
  assert.deepEqual(
    inspectJpeg(Uint8Array.from([...BASELINE_JPEG, 0xff, 0xd9])),
    { code: "jpeg_structure_invalid", ok: false },
  );
});

test("TASK-137 JPEG parser rejects malformed Huffman trees and missing table bindings", () => {
  const firstDhtOffset = markerOffset(BASELINE_JPEG, 0xc4);
  const sofOffset = markerOffset(BASELINE_JPEG, 0xc0);
  const sosOffset = markerOffset(BASELINE_JPEG, 0xda);
  assert.notEqual(firstDhtOffset, -1);
  assert.notEqual(sofOffset, -1);
  assert.notEqual(sosOffset, -1);

  const oversubscribedDht = replaceSegment(BASELINE_JPEG, firstDhtOffset, [
    0xff,
    0xc4,
    0x00,
    0x16,
    0x00,
    0x03,
    ...Array(15).fill(0),
    0x00,
    0x09,
    0x0a,
  ]);
  const allOnesDht = copyBytes(BASELINE_JPEG);
  allOnesDht[firstDhtOffset + 5] = 0x02;
  allOnesDht[firstDhtOffset + 6] = 0x00;
  const missingDcTable = copyBytes(BASELINE_JPEG);
  missingDcTable[firstDhtOffset + 4] = 0x10;
  const missingQuantizationTable = copyBytes(BASELINE_JPEG);
  missingQuantizationTable[sofOffset + 12] = 0x03;

  for (const malformed of [
    oversubscribedDht,
    allOnesDht,
    missingDcTable,
    missingQuantizationTable,
  ]) {
    assert.deepEqual(inspectJpeg(malformed), {
      code: "jpeg_structure_invalid",
      ok: false,
    });
  }

  for (const selector of [0x22, 0xf0]) {
    const malformedSelector = copyBytes(BASELINE_JPEG);
    malformedSelector[sosOffset + 6] = selector;
    assert.deepEqual(inspectJpeg(malformedSelector), {
      code: "jpeg_structure_invalid",
      ok: false,
    });
  }
});

